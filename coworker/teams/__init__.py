def __getattr__(name: str):
    """Load legacy board tools only when that surface is explicitly requested.

    Canonical Team records and runtime imports must remain inspectable without
    importing the optional aisuite-backed legacy tool wrappers.
    """
    if name in {"board_tools", "journal_tools"}:
        from .tools import board_tools, journal_tools

        globals().update(board_tools=board_tools, journal_tools=journal_tools)
        return globals()[name]
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")

